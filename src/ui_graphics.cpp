void DrawBitmap(OneBitGraphicsDisplay* disp, int x, int y, int w, int h, const uint8_t* bits)
{
    const int stride = (w + 7) / 8;
    for(int row = 0; row < h; row++)
        for(int col = 0; col < w; col++)
            if(bits[row * stride + col / 8] & (0x80 >> (col % 8)))
                disp->DrawPixel(x + col, y + row, true);
}
